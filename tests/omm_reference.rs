//! Cross-checks OMM ingestion and propagation against an **independent** implementation.
//!
//! The fixtures in `tests/data/omm/` are:
//!
//! - `mario.xml` and `mario.csv`: CelesTrak's OMM for object 55123 (MARIO), exactly as served
//!   in `FORMAT=XML` and `FORMAT=CSV`, with the TLE published for the same element set below.
//!   This element set has no zero field, so a wrong unit conversion cannot hide behind a zero.
//!   The same three samples are used by python-sgp4's own test suite.
//! - `high_catalog.json`: three **synthetic** objects (not real satellites) in CelesTrak's
//!   JSON layout, numbered 100123, 340000 and 799500123: beyond the TLE's five digits, beyond
//!   Alpha-5, and at the nine-digit limit. They cover a low orbit, a 12-hour Molniya orbit and
//!   a geostationary orbit, so both the near-Earth and the deep-space branches of SGP4 run.
//! - `reference_states.csv`: TEME position and velocity for all four objects at twelve offsets
//!   from epoch, generated by `make_reference.py` with python-sgp4 (the reference C++ SGP4 of
//!   Vallado et al.) using WGS84 constants.
//!
//! Both sides read the same files, so a disagreement can only come from how Ephemerust reads
//! the OMM or hands it to the propagator. Measured worst case over the 48 samples (offsets of
//! -1 to +2 days): **0.024 mm** in position and **0.008 µm/s** in velocity, which is the
//! rounding of the reference file. The test bounds are 1 mm and 1 µm/s.

use chrono::Duration;
use ephemerust::omm::{Omm, OmmFormat, select_omm};
use ephemerust::{ObserverLocation, Propagator, Tle};

const MARIO_XML: &str = include_str!("data/omm/mario.xml");
const MARIO_CSV: &str = include_str!("data/omm/mario.csv");
const HIGH_CATALOG_JSON: &str = include_str!("data/omm/high_catalog.json");
const REFERENCE: &str = include_str!("data/omm/reference_states.csv");

/// The TLE CelesTrak published for the same MARIO element set.
const MARIO_TLE: &str = "MARIO\n\
    1 55123U 98067UQ  23115.44827133  .00787702  29408-3  15680-2 0  9999\n\
    2 55123  51.6242 216.2930 0014649 331.8976  28.1241 15.99081912 18396";

fn all_fixture_messages() -> Vec<Omm> {
    let mut all = Omm::parse_all(MARIO_XML).expect("mario.xml");
    all.extend(Omm::parse_all(HIGH_CATALOG_JSON).expect("high_catalog.json"));
    all
}

#[test]
fn celestrak_xml_and_csv_describe_the_same_object() {
    assert_eq!(OmmFormat::detect(MARIO_XML), Some(OmmFormat::Xml));
    assert_eq!(OmmFormat::detect(MARIO_CSV), Some(OmmFormat::Csv));

    let from_xml = Omm::parse(MARIO_XML).expect("mario.xml");
    let from_csv = Omm::parse(MARIO_CSV).expect("mario.csv");
    assert_eq!(from_xml, from_csv);

    assert_eq!(from_xml.name.as_deref(), Some("MARIO"));
    assert_eq!(
        from_xml.international_designator.as_deref(),
        Some("1998-067UQ")
    );
    assert_eq!(from_xml.catalog_number, Some(55123));
    assert_eq!(from_xml.mean_motion, 15.99081912);
    assert_eq!(from_xml.eccentricity, 0.0014649);
    assert_eq!(from_xml.bstar, 0.1568e-2);
    assert_eq!(from_xml.mean_motion_dot, 0.787702e-2);
    assert_eq!(from_xml.mean_motion_ddot, 0.29408e-3);
    assert_eq!(from_xml.revolution_number, 1839);
}

#[test]
fn celestrak_omm_carries_the_same_elements_as_its_tle() {
    let tle = Tle::parse(MARIO_TLE).expect("MARIO TLE");
    let from_tle = Omm::from(&tle);
    let mut omm = Omm::parse(MARIO_XML).expect("mario.xml");

    // Epoch: eight-decimal day fraction (TLE) against microseconds (OMM).
    let delta_us = (omm.epoch - tle.epoch).num_microseconds().expect("small");
    assert!(delta_us.abs() <= 1, "epochs differ by {delta_us} µs");

    omm.epoch = from_tle.epoch;
    assert_eq!(omm, from_tle);
}

#[test]
fn omm_and_tle_propagate_to_the_same_state() {
    let tle = Tle::parse(MARIO_TLE).expect("MARIO TLE");
    let omm = Omm::parse(MARIO_CSV).expect("mario.csv");
    let from_tle = Propagator::new(&tle).expect("TLE propagator");
    let from_omm = Propagator::from_omm(&omm).expect("OMM propagator");

    // The epochs differ by up to 1 µs (see above), which at 7.7 km/s is under a centimetre.
    let mut worst_m = 0.0_f64;
    for minutes in [-720, -90, 0, 1, 45, 90, 720, 1440] {
        let t = tle.epoch + Duration::minutes(minutes);
        let a = from_tle.propagate(t).expect("TLE state");
        let b = from_omm.propagate(t).expect("OMM state");
        let d = (0..3)
            .map(|i| (a.position_km[i] - b.position_km[i]).powi(2))
            .sum::<f64>()
            .sqrt()
            * 1000.0;
        worst_m = worst_m.max(d);
    }
    assert!(
        worst_m < 0.02,
        "worst TLE/OMM position difference {worst_m} m"
    );
}

#[test]
fn states_match_the_python_sgp4_reference() {
    let messages = all_fixture_messages();
    assert_eq!(messages.len(), 4);

    let (mut worst_pos_m, mut worst_vel_mm_s) = (0.0_f64, 0.0_f64);
    let mut rows = 0;
    for line in REFERENCE.lines().filter(|l| !l.starts_with('#')) {
        let cols: Vec<&str> = line.split(',').collect();
        assert_eq!(cols.len(), 8, "malformed reference row: {line}");
        let catalog: u32 = cols[0].parse().expect("catalog number");
        let minutes: i64 = cols[1].parse().expect("minutes");
        let expected: Vec<f64> = cols[2..]
            .iter()
            .map(|c| c.parse().expect("number"))
            .collect();

        let omm = messages
            .iter()
            .find(|m| m.catalog_number == Some(catalog))
            .unwrap_or_else(|| panic!("no fixture message for catalog {catalog}"));
        let prop = Propagator::from_omm(omm).expect("propagator");
        let state = prop
            .propagate(omm.epoch + Duration::minutes(minutes))
            .unwrap_or_else(|e| panic!("catalog {catalog} at {minutes} min: {e}"));

        let pos_m = (0..3)
            .map(|i| (state.position_km[i] - expected[i]).powi(2))
            .sum::<f64>()
            .sqrt()
            * 1000.0;
        let vel_mm_s = (0..3)
            .map(|i| (state.velocity_km_s[i] - expected[3 + i]).powi(2))
            .sum::<f64>()
            .sqrt()
            * 1.0e6;
        worst_pos_m = worst_pos_m.max(pos_m);
        worst_vel_mm_s = worst_vel_mm_s.max(vel_mm_s);
        rows += 1;
    }
    assert_eq!(rows, 48, "expected 4 objects x 12 offsets");
    assert!(
        worst_pos_m < 1.0e-3,
        "worst position difference {worst_pos_m} m exceeds 1 mm"
    );
    assert!(
        worst_vel_mm_s < 1.0e-3,
        "worst velocity difference {worst_vel_mm_s} mm/s exceeds 1 µm/s"
    );
}

#[test]
fn high_catalog_objects_are_selected_and_tracked() {
    let leo = select_omm(HIGH_CATALOG_JSON, Some("100123")).expect("six digits");
    let molniya = select_omm(HIGH_CATALOG_JSON, Some("molniya")).expect("by name");
    let geo = select_omm(HIGH_CATALOG_JSON, Some("799500123")).expect("nine digits");
    assert_eq!(leo.name.as_deref(), Some("EXAMPLE-LEO"));
    assert_eq!(molniya.catalog_number, Some(340_000));
    assert_eq!(geo.name.as_deref(), Some("EXAMPLE-GEO"));

    // A day of passes for the low orbit over a mid-latitude station.
    let station = ObserverLocation {
        latitude: 47.9088,
        longitude: -122.2503,
        elevation: 0.0,
    };
    let prop = Propagator::from_omm(&leo).expect("propagator");
    let passes = prop
        .predict_passes(station, leo.epoch, leo.epoch + Duration::hours(24), 10.0)
        .expect("passes");
    assert!(
        (2..=8).contains(&passes.len()),
        "a sun-synchronous orbit gives a mid-latitude station a handful of passes a day, got {}",
        passes.len()
    );
    for pass in &passes {
        assert!(pass.aos < pass.culmination && pass.culmination < pass.los);
        assert!(pass.max_elevation_deg >= 10.0);
        let minutes = (pass.los - pass.aos).num_seconds() as f64 / 60.0;
        assert!((0.5..15.0).contains(&minutes), "pass lasts {minutes} min");
    }

    // The geostationary object stays put: seen from beneath it, one pass spans the window.
    let prop = Propagator::from_omm(&geo).expect("propagator");
    let below = prop.subpoint(geo.epoch).expect("subpoint");
    assert!((35_700.0..35_900.0).contains(&below.altitude_km));
    let station = ObserverLocation {
        latitude: below.latitude_deg,
        longitude: below.longitude_deg,
        elevation: 0.0,
    };
    let (start, end) = (geo.epoch, geo.epoch + Duration::hours(6));
    let passes = prop
        .predict_passes(station, start, end, 10.0)
        .expect("passes");
    assert_eq!(passes.len(), 1);
    assert_eq!((passes[0].aos, passes[0].los), (start, end));
    assert!(passes[0].max_elevation_deg > 85.0);
}
