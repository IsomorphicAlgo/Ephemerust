"""Regenerates reference_states.csv with python-sgp4 (pip install sgp4).

python-sgp4 wraps the reference C++ SGP4 of Vallado et al. (2006), so its states are
independent of the Rust `sgp4` crate that Ephemerust propagates with. Both sides read the same
OMM files; this script uses python-sgp4's own OMM readers for the XML and the standard
library's JSON reader for the JSON.

Run from this directory:  python3 make_reference.py > reference_states.csv
"""
import json

import sgp4
from sgp4 import omm
from sgp4.api import WGS84, Satrec

# Minutes from each element set's epoch, backwards and forwards.
OFFSETS = [-1440, -360, -90, 0, 1, 10, 45, 90, 360, 720, 1440, 2880]


def messages():
    with open("mario.xml") as f:
        yield from omm.parse_xml(f)
    with open("high_catalog.json") as f:
        for fields in json.load(f):
            yield {key: str(value) for key, value in fields.items()}


print("# Independent reference TEME states for the OMM fixtures in this directory.")
print(f"# Generated by make_reference.py with python-sgp4 {sgp4.__version__} (Vallado C++ SGP4),")
print("# WGS84 constants, improved mode: the same model as PropagationModel::Modern.")
print("# Columns: NORAD_CAT_ID, minutes from epoch, x km, y km, z km, vx km/s, vy km/s, vz km/s")
for fields in messages():
    sat = Satrec()
    # python-sgp4 stores the catalog number in its Alpha-5 field and refuses anything above
    # 339999. SGP4 never reads the number, so larger ones are initialised as 0.
    usable = dict(fields)
    if int(fields["NORAD_CAT_ID"]) > 339999:
        usable["NORAD_CAT_ID"] = "0"
    omm.initialize(sat, usable, WGS84)
    for minutes in OFFSETS:
        error, r, v = sat.sgp4_tsince(float(minutes))
        if error:
            continue  # e.g. a decayed orbit; Ephemerust must report an error there too
        print(fields["NORAD_CAT_ID"], minutes, *(f"{c:.9f}" for c in r), *(f"{c:.12f}" for c in v), sep=",")
